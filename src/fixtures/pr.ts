  '/** Finds a zone by id; null when the facility does not know it. */',
  'export async function findZone(client: ParcsClient, id: ZoneId): Promise<Zone | null> {',
  '  const zones = await client.listZones();',
  '  const zone = zones.find((candidate) => candidate.id === id);',
  '  return zone ?? null;',
  '}',
  '',
  'export function isOpen(zone: Zone, now: Date): boolean {',
  '  const minutes = now.getHours() * 60 + now.getMinutes();',
  '  return minutes >= toMinutes(zone.opensAt) && minutes < toMinutes(zone.closesAt);',
  '}',
  '',
  'export async function switchZone(client: ParcsClient, from: ZoneId, to: ZoneId): Promise<void> {',
  '  const target = await findZone(client, to);',
  '  if (!target) throw new Error(`Unknown zone ${to}`);',
  '  if (!isOpen(target, new Date())) {',
  '    throw new Error(`${target.name} is closed`);',
  '  }',
  "  await client.post('/zones/switch', { from, to });",
  '}',
  '',
  'function toMinutes(time: string): number {',
  "  const [hours = '0', minutes = '0'] = time.split(':');",
  '  return Number(hours) * 60 + Number(minutes);',
  '}',
  '',
